code = bytearray([
  0xa9, 0xFF,         # lda #$ff
  0x8d, 0x02, 0x90,   # to DDRB

  0xa9, 0x30,         
  0x8d, 0x00, 0x90,   
  
  0xa9, 0x39,          
  0x8d, 0x00, 0x90,   # clearing instructions X3
  
  0xa9, 0x30,         
  0x8d, 0x00, 0x90,   
  
  0xa9, 0x39,          
  0x8d, 0x00, 0x90,   
  
  0xa9, 0x30,         
  0x8d, 0x00, 0x90,   # 2
  
  0xa9, 0x39,          
  0x8d, 0x00, 0x90,   
  
  0xa9, 0x30,         
  0x8d, 0x00, 0x90,   # 3

  0xa9, 0x29,          
  0x8d, 0x00, 0x90,   
  
  0xa9, 0x20,        # Send 4 bit command (only once xmit since currently in 8 bit mode) 
  0x8d, 0x00, 0x90,   
  
  0xa9, 0x29,          
  0x8d, 0x00, 0x90,   
  
  0xa9, 0x20,        # Send 4 bit command high nibble ( 2 xmit since now in 4 bit mode) 
  0x8d, 0x00, 0x90,
  
  0xa9, 0x09,          
  0x8d, 0x00, 0x90,   
  
  0xa9, 0x00,        # Send 4 bit command low nibble 
  0x8d, 0x00, 0x90,
  
  0xa9, 0x09,          
  0x8d, 0x00, 0x90,   # On Display high nibble
  
  0xa9, 0x00,         
  0x8d, 0x00, 0x90,   
  
  0xa9, 0xE9,         
  0x8d, 0x00, 0x90,   

  0xa9, 0xE0,         
  0x8d, 0x00, 0x90,   # On Display low nibble
  
  0xa9, 0x09,          
  0x8d, 0x00, 0x90,   
  
  0xa9, 0x00,         
  0x8d, 0x00, 0x90,   # Entry Mode Set high nibble
  
  0xa9, 0x69,         
  0x8d, 0x00, 0x90,   

  0xa9, 0x60,         
  0x8d, 0x00, 0x90,   # Entry Mode Set low nibble
  
  0xa9, 0x4B,          
  0x8d, 0x00, 0x90,   
  
  0xa9, 0x42,         
  0x8d, 0x00, 0x90,   # B high nibble
  
  0xa9, 0x2B,         
  0x8d, 0x00, 0x90,   

  0xa9, 0x22,         
  0x8d, 0x00, 0x90,   # B low nibble
  
  0xa9, 0x5B,          
  0x8d, 0x00, 0x90,   
  
  0xa9, 0x52,         
  0x8d, 0x00, 0x90,   # R high nibble
  
  0xa9, 0x2B,         
  0x8d, 0x00, 0x90,   

  0xa9, 0x22,         
  0x8d, 0x00, 0x90,   # R low nibble

  0x4c, 0x05, 0xa0,   # jmp $a005 # MODIFIED HERE - different code start address, so different jump target
  ])

# MODIFIED BELOW - first 8KB of ROM are not really used, but need to be filled out; actual ROM starts at address
# 0xa000 and is of 24KB length
rom = bytearray([0xea] * 8192) + code + bytearray([0xea] * (24576 - len(code)))

rom[0x7ffc] = 0x00
rom[0x7ffd] = 0xa0 # MODIFIED HERE - different code start address

with open("rom_lcd.bin", "wb") as out_file:
  out_file.write(rom)